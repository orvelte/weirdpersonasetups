"""Stage 1 reference library: Qwen3.5 answers all 200 questions under each of the 30 persona system prompts.
Thinking OFF, max_tokens 350, temperature/top_p from harness defaults, 1 sample. 6,000 generations. Resumable
(skips (persona, qid) pairs already in results/T11/reference.jsonl). Run: python3 -m tasks.T11.gen_reference [--limit N]
Self-match test: --version 3.8 writes the same library generated by Qwen3.8 to results/T11/reference_3.8.jsonl (spend tag T11_ref38)."""
import sys, time
from harness import config
from harness.client import total_spend
from tasks.T11.common import load_questions, load_personas, frame_messages, safe_chat_many, read_jsonl, append_jsonl, OUT

REF_VERSION = sys.argv[sys.argv.index("--version") + 1] if "--version" in sys.argv else "3.5"
REF_TAG = "T11_ref" if REF_VERSION == "3.5" else "T11_ref" + REF_VERSION.replace(".", "")
REF_PATH = "reference.jsonl" if REF_VERSION == "3.5" else f"reference_{REF_VERSION}.jsonl"
MAX_TOKENS = 350
BATCH = 150

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    limit = int(sys.argv[sys.argv.index("--limit") + 1]) if "--limit" in sys.argv else None
    qs = load_questions(); personas = load_personas()["personas"]
    path = OUT / REF_PATH
    done = {(r["persona"], r["qid"]) for r in read_jsonl(path) if not r.get("error")}
    todo = [(p, q) for p in personas for q in qs if (p, q["id"]) not in done]
    if limit: todo = todo[:limit]
    print(f"version {REF_VERSION} -> {path} (tag {REF_TAG}); {len(personas)} personas x {len(qs)} questions; {len(done)} done, {len(todo)} to run; spend before ${total_spend():.3f}")
    t0 = time.time()
    for b in range(0, len(todo), BATCH):
        chunk = todo[b:b + BATCH]
        jobs = [{"version": REF_VERSION, "messages": frame_messages("chat", q["messages"], system=personas[p]), "sample": 0}
                for p, q in chunk]
        res = safe_chat_many(jobs, task=REF_TAG, workers=16, thinking=False, max_tokens=MAX_TOKENS)
        recs = []
        for (p, q), r in zip(chunk, res):
            if r.get("error"):
                recs.append({"persona": p, "qid": q["id"], "kind": q["kind"], "family": q["family"], "error": r["error"]}); continue
            recs.append({"persona": p, "qid": q["id"], "kind": q["kind"], "family": q["family"], "version": REF_VERSION,
                         "model_id": r.get("model_id"), "provider": r.get("provider"), "content": r["content"],
                         "truncated": int(bool(r["truncated"])), "finish_reason": r["finish_reason"], "usage": r["usage"],
                         "cost": r.get("cost", 0), "cached": r.get("cached")})
        append_jsonl(path, recs)
        nerr = sum(1 for r in recs if r.get("error"))
        print(f"batch {b // BATCH + 1}: {len(recs)} written ({nerr} errors); {time.time() - t0:.0f}s; spend ${total_spend():.3f}", flush=True)
        if any(r.get("error") == "task budget exceeded" for r in recs):
            print("TASK BUDGET EXCEEDED, stopping"); break
    print(f"done; spend after ${total_spend():.3f}")

if __name__ == "__main__":
    main()
